class Encoder(nn.Module):

    def __init__(self, latent_channels=8):
        super().__init__()

        # TODO 1 completed
        self.network = nn.Sequential(
            nn.Conv2d(
                in_channels=1,
                out_channels=16,
                kernel_size=3,
                stride=2,
                padding=1
            ),
            nn.ReLU(),

            nn.Conv2d(
                in_channels=16,
                out_channels=32,
                kernel_size=3,
                stride=2,
                padding=1
            ),
            nn.ReLU(),

            nn.Conv2d(
                in_channels=32,
                out_channels=latent_channels,
                kernel_size=1,
                stride=1,
                padding=0
            )
        )

    def forward(self, x):
        return self.network(x)


# ------------------------------------------------------------
# 4. DECODER
# ------------------------------------------------------------

class Decoder(nn.Module):

    def __init__(self, latent_channels=8):
        super().__init__()

        # TODO 2 completed
        self.network = nn.Sequential(

            nn.ConvTranspose2d(
                in_channels=latent_channels,
                out_channels=16,
                kernel_size=3,
                stride=2,
                padding=1,
                output_padding=1
            ),
            nn.ReLU(),

            nn.ConvTranspose2d(
                in_channels=16,
                out_channels=1,
                kernel_size=3,
                stride=2,
                padding=1,
                output_padding=1
            ),
            nn.Sigmoid()
        )

    def forward(self, z):
        return self.network(z)


# ------------------------------------------------------------
# 5. COMBINED ENCODER-DECODER
# ------------------------------------------------------------

class ImageEncoderDecoder(nn.Module):

    def __init__(self, latent_channels=8):
        super().__init__()

        self.encoder = Encoder(latent_channels)
        self.decoder = Decoder(latent_channels)

    def forward(self, x):

        # TODO 3 completed
        z = self.encoder(x)
        reconstruction = self.decoder(z)

        return reconstruction, z


