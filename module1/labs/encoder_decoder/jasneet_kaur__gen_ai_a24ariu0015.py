# Input: 28 x 28
#
# Conv2d formula:
# H_out = floor((H + 2P - D(K-1) - 1)/S + 1)
#
# Encoder 1:
# H = floor((28 + 2*1 - 1*(3-1) - 1)/2 + 1)
#   = 14
#
# Encoder 2:
# H = floor((14 + 2*1 - 2 - 1)/2 + 1)
#   = 7
#
# Bottleneck:
# kernel=1, stride=1, padding=0 -> remains 7x7
#
# Decoder:
# H_out = (H-1)*stride - 2*padding + kernel + output_padding
#       = (7-1)*2 - 2*1 + 3 + 1
#       = 14
#
# Second decoder:
#       = (14-1)*2 - 2*1 + 3 + 1
#       = 28

print("Input:       [N, 1, 28, 28]")
print("Encoder 1:  [N, 16, 14, 14]")
print("Encoder 2:  [N, 32, 7, 7]")
print(f"Bottleneck:  [N, {LATENT_CHANNELS}, 7, 7]")
print("Decoder 1:  [N, 16, 14, 14]")
print("Decoder 2:  [N, 1, 28, 28]")

input_values = 1 * 28 * 28

