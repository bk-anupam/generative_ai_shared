criterion = nn.MSELoss()


def train_step(model, images, optimizer, criterion):

    # TODO 4 completed

    # Clear old gradients
    optimizer.zero_grad()

    # Forward pass
    reconstruction, z = model(images)

    # Reconstruction loss
    loss = criterion(reconstruction, images)

    # Backpropagation
    loss.backward()

    # Update parameters
    optimizer.step()

    # Return Python number
    return loss.item()


# ------------------------------------------------------------
# 8. EVALUATION
# ------------------------------------------------------------

@torch.no_grad()
def evaluate(model, loader):

    model.eval()

    total_loss = 0.0

    for images, _ in loader:

        images = images.to(device)

        reconstruction, _ = model(images)

        total_loss += (
            criterion(reconstruction, images).item()
            * images.size(0)
        )

    return total_loss / len(loader.dataset)


