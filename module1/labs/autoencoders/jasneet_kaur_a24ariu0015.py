# 14. TRAINING STEP
# ============================================================

def train_step(
    model,
    batch,
    optimizer,
    beta
):

    batch = batch.to(
        DEVICE,
        non_blocking=True
    )

    optimizer.zero_grad(
        set_to_none=True
    )

    reconstruction, mu, logvar = model(
        batch
    )

    total_loss, reconstruction_loss, kl_loss = vae_loss(
        reconstruction,
        batch,
        mu,
        logvar,
        beta
    )

    total_loss.backward()

    optimizer.step()

    return (
        total_loss.item(),
        reconstruction_loss.item(),
        kl_loss.item()
    )


