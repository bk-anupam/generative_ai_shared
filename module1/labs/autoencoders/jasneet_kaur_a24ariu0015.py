@torch.no_grad()
def evaluate(
    model,
    loader,
    beta
):

    model.eval()

    totals = np.zeros(
        3,
        dtype=np.float64
    )

    examples = 0

    for batch in loader:

        batch = batch.to(
            DEVICE,
            non_blocking=True
        )

        reconstruction, mu, logvar = model(
            batch
        )

        values = vae_loss(
            reconstruction,
            batch,
            mu,
            logvar,
            beta
        )

        batch_size = batch.size(0)

        totals += np.array([
            value.item()
            for value in values
        ]) * batch_size

        examples += batch_size

    return totals / examples


