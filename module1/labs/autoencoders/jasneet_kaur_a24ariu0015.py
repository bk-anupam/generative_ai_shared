class DenseFaceVAE(nn.Module):

    def __init__(
        self,
        input_dim=INPUT_DIM,
        latent_dim=LATENT_DIM
    ):

        super().__init__()

        self.input_dim = input_dim
        self.latent_dim = latent_dim

        # -------------------------------
        # Encoder
        # -------------------------------

        self.encoder = nn.Sequential(

            nn.Linear(
                input_dim,
                1500
            ),

            nn.ReLU(),

            nn.Linear(
                1500,
                1000
            ),

            nn.ReLU()
        )


        # -------------------------------
        # Mean and log variance heads
        # -------------------------------

        self.mu_head = nn.Linear(
            1000,
            latent_dim
        )

        self.logvar_head = nn.Linear(
            1000,
            latent_dim
        )


        # -------------------------------
        # Decoder
        # -------------------------------

        self.decoder = nn.Sequential(

            nn.Linear(
                latent_dim,
                1000
            ),

            nn.ReLU(),

            nn.Linear(
                1000,
                1500
            ),

            nn.ReLU(),

            nn.Linear(
                1500,
                input_dim
            ),

            nn.Sigmoid()
        )


    # ========================================================
    # ENCODER
    # ========================================================

    def encode(self, x):

        features = self.encoder(
            x.flatten(start_dim=1)
        )

        mu = self.mu_head(
            features
        )

        logvar = self.logvar_head(
            features
        )

        return mu, logvar


    # ========================================================
    # REPARAMETERIZATION TRICK
    # ========================================================

    def reparameterize(
        self,
        mu,
        logvar
    ):

        # std = exp(0.5 * log variance)

        std = torch.exp(
            0.5 * logvar
        )

        # Random noise

        epsilon = torch.randn_like(
            std
        )

        # Reparameterization trick

        z = mu + epsilon * std

        return z


    # ========================================================
    # DECODER
    # ========================================================

    def decode(self, z):

        pixels = self.decoder(z)

        return pixels.view(
            -1,
            CHANNELS,
            IMAGE_SIZE,
            IMAGE_SIZE
        )


    # ========================================================
    # FORWARD
    # ========================================================

    def forward(self, x):

        mu, logvar = self.encode(x)

        z = self.reparameterize(
            mu,
            logvar
        )

        reconstruction = self.decode(
            z
        )

        return reconstruction, mu, logvar


