# 12. VAE LOSS
# ============================================================

def vae_loss(
    reconstruction,
    target,
    mu,
    logvar,
    beta=1.0
):

    # Reconstruction loss

    reconstruction_loss = F.binary_cross_entropy(
        reconstruction,
        target,
        reduction="sum"
    )


    # KL divergence

    kl_loss = -0.5 * torch.sum(
        1
        + logvar
        - mu.pow(2)
        - logvar.exp()
    )


    # Normalize by batch size

    batch_size = target.size(0)

    reconstruction_loss = (
        reconstruction_loss
        / batch_size
    )

    kl_loss = (
        kl_loss
        / batch_size
    )


    # Total VAE loss

    total_loss = (
        reconstruction_loss
        + beta * kl_loss
    )


    return (
        total_loss,
        reconstruction_loss.detach(),
        kl_loss.detach()
    )


